"""Generate capability-by-difficulty and source-diversity coverage reporting."""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict

from core.capabilities import (
    capability_names_for_case,
    load_capability_index,
    validate_capability_index,
)
from config import BENCHMARKS_JSON, PROJECT_ROOT
from core.evaluator import load_specs


CAPABILITY_REPORT_PATH = PROJECT_ROOT / "docs" / "capability_coverage.md"


def _case_link(spec: dict) -> str:
    path = PROJECT_ROOT.joinpath(spec["_path"]).resolve().relative_to(PROJECT_ROOT)
    return f"[`{spec['name']}`](../{path.as_posix()})"


def render_capability_report() -> str:
    specs = load_specs(BENCHMARKS_JSON)
    by_name = {spec["name"]: spec for spec in specs}
    index = load_capability_index()
    errors = validate_capability_index(index, specs)
    if errors:
        raise ValueError("invalid capability index:\n- " + "\n- ".join(errors))

    tagged: dict[str, list[dict]] = defaultdict(list)
    primary: dict[str, list[dict]] = defaultdict(list)
    for name, assignment in index["cases"].items():
        spec = by_name[name]
        primary[assignment["primary"]].append(spec)
        for capability in capability_names_for_case(index, name):
            tagged[capability].append(spec)

    lines = [
        "# FinAgenticBench capability coverage",
        "",
        "<!-- Generated by python -m scripts.capability_coverage --write; do not edit by hand. -->",
        "",
        "This is a secondary index over the task-family case taxonomy. It is used only for "
        "sampling, capability-level reporting, and finding coverage gaps; it is not a case quota and "
        "does not replace task-family or financial-domain metadata.",
        "",
        f"**{len(specs)} active cases; {len(index['families'])} controlled capability families.** "
        "Every case has one primary capability and at most three secondary capabilities.",
        "",
        "Difficulty counts below include every case tagged with the capability, whether primary or "
        "secondary. `Sources` counts distinct dataset identifiers, not files.",
        "",
        "## Coverage matrix",
        "",
        "| Capability | Primary | All tagged | Easy | Medium | Hard | Baseline | Trap | Sources |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for family_id, family in index["families"].items():
        selected = tagged[family_id]
        levels = Counter(spec["difficulty"] for spec in selected)
        types = Counter(spec["case_type"] for spec in selected)
        sources = {source for spec in selected for source in spec["data_sources"]}
        lines.append(
            f"| {family['label']} (`{family_id}`) | {len(primary[family_id])} | "
            f"{len(selected)} | {levels['easy']} | {levels['medium']} | {levels['hard']} | "
            f"{types['baseline']} | {types['trap']} | {len(sources)} |"
        )

    lines.extend(["", "## Primary assignments", ""])
    for family_id, family in index["families"].items():
        selected = sorted(
            primary[family_id],
            key=lambda spec: ({"easy": 0, "medium": 1, "hard": 2}[spec["difficulty"]], spec["name"]),
        )
        rendered = "; ".join(
            f"{_case_link(spec)} ({spec['difficulty']}, {spec['case_type']})"
            for spec in selected
        )
        lines.extend([
            f"### {family['label']}",
            "",
            family["definition"],
            "",
            rendered,
            "",
        ])

    lines.extend([
        "## Review indicators",
        "",
        "These are review prompts, not automatic defects. A narrow capability may legitimately be "
        "source-specific, and a missing easy case is not a reason to manufacture one.",
        "",
    ])
    indicators: list[str] = []
    for family_id, family in index["families"].items():
        selected = tagged[family_id]
        levels = Counter(spec["difficulty"] for spec in selected)
        source_case_counts = Counter()
        for spec in selected:
            source_case_counts.update(set(spec["data_sources"]))
        if not selected:
            indicators.append(
                f"- **Empty:** {family['label']} has no active tagged case."
            )
            continue
        dominant_source, dominant_count = source_case_counts.most_common(1)[0]
        dominance = dominant_count / len(selected)
        if len(selected) <= 3:
            indicators.append(
                f"- **Sparse:** {family['label']} has only {len(selected)} tagged cases."
            )
        if dominance >= 0.75 and len(selected) >= 3:
            indicators.append(
                f"- **Source concentration:** {family['label']} has {dominant_count}/{len(selected)} "
                f"tagged cases using `{dominant_source}`."
            )
        missing = [level for level in ("easy", "medium", "hard") if not levels[level]]
        if missing:
            indicators.append(
                f"- **Difficulty gap:** {family['label']} has no {', '.join(missing)} tagged case."
            )
    lines.extend(indicators or ["No automatic review indicators."])

    lines.extend([
        "",
        "## Usage rules",
        "",
        "- Sample by primary capability when constructing a balanced diagnostic slice; use secondary "
        "tags only to prevent hidden over- or under-coverage.",
        "- Report both case-level results and capability-level results. A capability score aggregates "
        "all tagged cases but must retain difficulty and source breakdowns.",
        "- Treat repeated source combinations as repeated evidence within those sources, not proof of "
        "broad transfer. Prefer a new necessary source role or a genuinely different phenomenon when "
        "strengthening coverage.",
        "- Do not create a case merely to fill an empty cell. New cases still pass the case-design "
        "standard and independent review gates.",
        "- Update `metadata/capabilities.json` whenever a case is added, retired, or materially changed, "
        "then regenerate this report.",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render_capability_report()
    if args.write:
        CAPABILITY_REPORT_PATH.write_text(rendered)
        print(f"wrote {CAPABILITY_REPORT_PATH}")
        return
    if not CAPABILITY_REPORT_PATH.exists() or CAPABILITY_REPORT_PATH.read_text() != rendered:
        raise SystemExit(
            "capability_coverage.md is stale; run "
            "python -m scripts.capability_coverage --write"
        )
    print(f"capability report is current: {CAPABILITY_REPORT_PATH}")


if __name__ == "__main__":
    main()
