"""Generate the machine-derived FinAgenticBench case catalog."""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path

from config import BENCHMARKS_JSON, PROJECT_ROOT
from core.evaluator import load_specs
from core.types import conversations_of
from core.taxonomy import load_case_taxonomy, validate_case_taxonomy


CATALOG_PATH = PROJECT_ROOT / "docs" / "benchmark_catalog.md"


def render_catalog() -> str:
    specs = load_specs(BENCHMARKS_JSON)
    taxonomy_index = load_case_taxonomy()
    errors = validate_case_taxonomy(taxonomy_index, specs)
    if errors:
        raise ValueError("invalid case taxonomy:\n- " + "\n- ".join(errors))
    assignments = taxonomy_index["cases"]
    difficulty = Counter(spec["difficulty"] for spec in specs)
    taxonomy = Counter(spec["case_type"] for spec in specs)
    source_modes = Counter(
        "single" if len(set(spec["data_sources"])) == 1 else "multi"
        for spec in specs
    )
    lines = [
        "# FinAgenticBench case catalog",
        "",
        "<!-- Generated by python -m scripts.catalog --write; do not edit by hand. -->",
        "",
        f"**{len(specs)} cases**: {taxonomy['baseline']} baselines / {taxonomy['trap']} diagnostic traps; "
        f"{difficulty['easy']} easy / {difficulty['medium']} medium / {difficulty['hard']} hard.",
        "",
        "## Task-family coverage",
        "",
        "| Task family | Cases | Baseline | Trap | Easy | Medium | Hard | Easy baseline |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for family in taxonomy_index["task_families"]:
        selected = [spec for spec in specs if spec["task_family"] == family]
        types = Counter(spec["case_type"] for spec in selected)
        levels = Counter(spec["difficulty"] for spec in selected)
        easy_baselines = sum(
            spec["difficulty"] == "easy" and spec["case_type"] == "baseline"
            for spec in selected
        )
        lines.append(
            f"| `{family}` | {len(selected)} | {types['baseline']} | {types['trap']} | "
            f"{levels['easy']} | {levels['medium']} | {levels['hard']} | {easy_baselines} |"
        )

    lines.extend([
        "",
        "## Source-mode coverage",
        "",
        "| Source mode | Cases |",
        "|---|---:|",
        f"| `single` | {source_modes['single']} |",
        f"| `multi` | {source_modes['multi']} |",
        "",
        "## Financial-domain coverage",
        "",
        "Domain counts are multi-label and therefore do not sum to the case count.",
        "",
        "| Financial domain | Cases |",
        "|---|---:|",
    ])
    for domain in taxonomy_index["financial_domains"]:
        count = sum(
            domain in assignments[spec["name"]]["financial_domains"]
            for spec in specs
        )
        lines.append(f"| `{domain}` | {count} |")

    lines.extend([
        "",
        "## Cases",
        "",
        "| Task family | Financial domains | Source mode | Case | Difficulty | Type | Sources | Claims |",
        "|---|---|---|---|---|---|---|---:|",
    ])
    for spec in sorted(specs, key=lambda item: (item["task_family"], item["name"])):
        path = Path(spec["_path"]).resolve().relative_to(PROJECT_ROOT)
        link = f"../{path.as_posix()}"
        sources = ", ".join(f"`{source}`" for source in spec["data_sources"])
        domains = ", ".join(
            f"`{domain}`"
            for domain in assignments[spec["name"]]["financial_domains"]
        )
        source_mode = "single" if len(set(spec["data_sources"])) == 1 else "multi"
        lines.append(
            f"| `{spec['task_family']}` | {domains} | `{source_mode}` | "
            f"[`{spec['name']}`]({link}) | {spec['difficulty']} | "
            f"{spec['case_type']} | {sources} | {sum(len(t.claims) for c in conversations_of(spec) for t in c.turns)} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render_catalog()
    if args.write:
        CATALOG_PATH.write_text(rendered)
        print(f"wrote {CATALOG_PATH}")
        return
    if not CATALOG_PATH.exists() or CATALOG_PATH.read_text() != rendered:
        raise SystemExit(
            "benchmark_catalog.md is stale; run python -m scripts.catalog --write"
        )
    print(f"catalog is current: {CATALOG_PATH}")


if __name__ == "__main__":
    main()
